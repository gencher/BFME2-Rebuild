void AISideBuildList::addInfo(BuildListInfo *info)
{
	if (m_head == 0)
	{
		m_head = info;
	}
	else
	{
		BuildListInfo *last = m_head;
		while (last)
		{
			if (last->m_next == 0)
				break;
			last = last->m_next;
		}
		last->m_next = info;
	}
	info->m_next = 0;
}

// FUNCTION: BFME2 0x002FD791 size=70 name=?parseScience@AI@@SAXPAVINI@@PAX1PBX@Z evidence=N:ledger
void AI::parseScience(INI *ini, void *instance, void *, const void *)
{
    TSkillSet *skillset = (TSkillSet *)instance;
    if (skillset->m_numSkills >= MAX_AI_UPGRADES) return;
    skillset->m_skills[skillset->m_numSkills] = SCIENCE_INVALID;
    INI::parseScience(ini, instance, skillset->m_skills + skillset->m_numSkills, 0);
    ScienceType science = skillset->m_skills[skillset->m_numSkills];
    if (science != SCIENCE_INVALID)
    {
        if (TheScienceStore->getSciencePurchaseCost(science) == 0) return;
        ++skillset->m_numSkills;
    }
}

