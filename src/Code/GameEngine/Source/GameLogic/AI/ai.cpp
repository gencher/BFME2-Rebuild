Object *AI::findClosestAlly(const Object *me, Real range, UnsignedInt flags)
{
	PartitionFilterRejectBuildings rejectBuildings((Object *)me);
	PartitionFilterRelationship relationship(me, 4, false);
	PartitionFilterAlive alive;
	PartitionFilterSameMapStatus sameMap(me);
	PartitionFilterLineOfSight lineOfSight(me);
	Rva002614DFFilter notMe(me);
	rejectBuildings.And(relationship.And(alive.And(sameMap.And(notMe))));
	if (flags & 1)
		rejectBuildings.And(lineOfSight);
	Object *found = ThePartitionManager->getClosestObject(me->getPosition(), range, FROM_CENTER_2D, &rejectBuildings);
	if (found == me)
		found = 0;
	return found;
}

