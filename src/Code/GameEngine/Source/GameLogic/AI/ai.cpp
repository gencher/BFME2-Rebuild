// FUNCTION: BFME2 0x002FEB3A size=125 name=?reset@AI@@UAEXXZ evidence=N:ledger
void AI::reset()
{
	m_pathfinder->reset();
	while (m_aiData && m_aiData->m_next)
	{
		TAiData *cur = m_aiData;
		m_aiData = m_aiData->m_next;
		::delete cur;
	}
	while (m_groupList.size())
	{
		AIGroup *group = m_groupList.front();
		if (group)
			destroyGroup(group);
		else
			m_groupList.pop_front();
	}
	m_nextGroupID = 0;
	m_nextFormationID = 1;
}

