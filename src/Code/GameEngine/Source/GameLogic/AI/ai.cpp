// FUNCTION: BFME2 0x002FDD0A size=138 name=?getAdjustedVisionRangeForObject@AI@@SAMPBVObject@@H@Z evidence=N:ledger
Real AI::getAdjustedVisionRangeForObject(const Object *obj, Int flags)
{
	Real range = obj->getVisionRange();
	const AIUpdateInterface *ai = obj->getAIUpdateInterface();
	if (ai == 0)
		return 0.0f;
	range = obj->getMajorRadius() + range;
	UnsignedInt mood = ai->getMoodMatrixValue();
	if (flags & 2)
	{
		if (mood & 1)
			return range;
		switch (mood & 0x1F00)
		{
		case 0x100:
			return 0.0f;
		case 0x800:
			range *= TheAI->getAiData()->m_alertRangeModifier;
			break;
		case 0x1000:
			range *= TheAI->getAiData()->m_aggressiveRangeModifier;
			break;
		}
	}
	return range;
}

