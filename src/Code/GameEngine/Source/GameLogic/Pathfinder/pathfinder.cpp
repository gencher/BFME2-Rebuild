// Pathfinder::iterateCellsAlongLine, cell form: Bresenham from start to end
// (Zero Hour's walk; BFME 2 steps the major axis by num/numadd/den and calls
// the callback once per cell).
template <class Callback>
Int Pathfinder::iterateCellsAlongLine(const ICoord2D *start, const ICoord2D *end, PathfindLayerEnum layer, Callback *callback)
{
	Int delta_x = abs(end->x - start->x);
	Int delta_y = abs(end->y - start->y);

	Int xinc2, yinc1, xinc1, numpixels, numadd, den;
	Int yinc2, num;
	if (delta_x >= delta_y)
	{
		numpixels = delta_x + 1;
		num = 2 * delta_y - delta_x;
		numadd = delta_y << 1;
		den = 2 * (delta_y - delta_x);
		xinc2 = 1;
		yinc2 = 0;
		yinc1 = 1;
		xinc1 = 1;
	}
	else
	{
		numpixels = delta_y + 1;
		num = 2 * delta_x - delta_y;
		numadd = delta_x << 1;
		den = 2 * (delta_x - delta_y);
		yinc2 = 1;
		xinc2 = 0;
		yinc1 = 1;
		xinc1 = 1;
	}

	if (start->x > end->x)
	{
		xinc2 = -xinc2;
		xinc1 = -1;
	}
	if (start->y > end->y)
	{
		yinc2 = -yinc2;
		yinc1 = -1;
	}

	Int x = start->x;
	Int y = start->y;
	PathfindCell *from = NULL;
	for (Int curpixel = 0; curpixel < numpixels; curpixel++)
	{
		PathfindCell *to = getCell(layer, x, y);
		if (to == NULL)
			return 0;

		Int ret = callback->cellCallback(from, to, x, y);
		if (ret != 0)
			return ret;
		from = to;

		if (num < 0)
		{
			num += numadd;
			x += xinc2;
			y += yinc2;
		}
		else
		{
			num += den;
			x += xinc1;
			y += yinc1;
		}
	}
	return 0;
}

