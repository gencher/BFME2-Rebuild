// FUNCTION: BFME2 0x0028D051 size=261 name=?getAbleToAttackSpecificObject@Object@@QBE?AW4CanAttackResult@@W4AbleToAttackType@@PBV1@W4CommandSourceType@@@Z evidence=N:ledger tier=A
// Zero Hour's is the weapon set's answer alone. BFME 2 first refuses a structure an
// object that cannot path through gates has no path to, a wall upgrade that declines,
// and lets a horde answer through one of its members.
CanAttackResult Object::getAbleToAttackSpecificObject(AbleToAttackType t, const Object *target, CommandSourceType cmdSource) const
{
	if (!target)
		return ATTACKRESULT_NOT_POSSIBLE;

	if (isKindOf(KINDOF_MACHINE) && !getTemplate()->m_canPathThroughGates && target->isKindOf(KINDOF_STRUCTURE))
	{
		if (!TheAI->pathfinder()->QuickDoesPathExistToStructure(const_cast<Object *>(this), getPosition(), const_cast<Object *>(target), 0))
			return ATTACKRESULT_NOT_POSSIBLE;
	}

	if (target->isKindOf(KINDOF_WALL_UPGRADE))
	{
		WallUpgradeUpdate *wall = WallUpgradeUpdate::rva004AB1F5(const_cast<Object *>(target));
		if (wall && !wall->rva004AB3AE())
			return ATTACKRESULT_NOT_POSSIBLE;
	}

	if (!(t & 0x10) && isKindOf(KINDOF_HORDE))
	{
		ContainModuleInterface *contain = m_contain;
		if (!contain)
			return ATTACKRESULT_NOT_POSSIBLE;
		HordeContainInterface *horde = contain->getHordeContainInterface();
		if (!horde)
			return ATTACKRESULT_NOT_POSSIBLE;
		if (testModelConditionState((ModelConditionFlagType)0x1BA) && target->isKindOf(KINDOF_WALL_SEGMENT))
			return ATTACKRESULT_NOT_POSSIBLE;
		Object *attacker = isKindOf(KINDOF_COMBO_HORDE) ? horde->rva0046CC09() : horde->rva0046D2C3(0xA4);
		if (attacker)
			return attacker->m_weaponSet.getAbleToAttackSpecificObject(t, attacker, target, cmdSource);
		return ATTACKRESULT_NOT_POSSIBLE;
	}

	return m_weaponSet.getAbleToAttackSpecificObject(t, this, target, cmdSource);
}

// FUNCTION: BFME2 0x0028D156 size=253 name=?getRelationship@Object@@QBE?AW4Relationship@@PBV1@@Z evidence=N:ledger tier=A
// Zero Hour's team relationship, after BFME 2's test that makes a target of kinds 55 and 2 an
// enemy of an attacker (this object, or the object its horde hands back) whose current weapon
// passes WeaponTemplate test 6.
Relationship Object::getRelationship(const Object *that) const
{
	if (that && that->getTemplate()->isKindOf((KindOfType)55) && that->getTemplate()->isKindOf((KindOfType)2))
	{
		const ThingTemplate *tmpl = getTemplate();
		if (tmpl->isKindOf((KindOfType)140) && m_modelConditions.testShifted(301))
			return ENEMIES;
		const Object *attacker = NULL;
		if (tmpl->isKindOf((KindOfType)133))
		{
			attacker = this;
		}
		else if (tmpl->isKindOf0x115() && rva0028C197())
		{
			const Object *rider = rva0028C197()->rva0046D27A();
			if (rider && rider->getTemplate()->isKindOf((KindOfType)133))
				attacker = rider;
		}
		if (attacker)
		{
			const Weapon *weapon = attacker->getCurrentWeapon();
			if (weapon && weapon->getTemplate()->rva002CA9CA(6, weapon))
				return ENEMIES;
		}
	}

	const Team *myTeam = getTeam();
	if (myTeam && that)
	{
		if (getIsUndetectedDefector())
			return NEUTRAL;
		else if (that->getIsUndetectedDefector())
			return ALLIES;
		else if (testModelConditionState((ModelConditionFlagType)0xCE) && getID() != that->getID())
			return ENEMIES;
		else
			return myTeam->getRelationship(that->getTeam());
	}

	return NEUTRAL;
}

