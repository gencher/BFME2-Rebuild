void Object::setTeam(Team *team)
{
	// In order to prevent spawning useful units for a player after he dies, we
	// just assign objects to the neutral player if we try to misbehave.
	if (team && !team->getControllingPlayer()->isPlayerActive())
		team = ThePlayerList->getNeutralPlayer()->getDefaultTeam();

	setTemporaryTeam(team);
	if (m_team)
	{
		m_originalTeamName = m_team->getPrototype() == NULL ? AsciiString::TheEmptyString : m_team->getPrototype()->m_ownerName;
		m_originalTeamName += '/';
		m_originalTeamName.concat(m_team->getPrototype() == NULL ? AsciiString::TheEmptyString : m_team->getPrototype()->getName());
	}
	else
	{
		m_originalTeamName.clear();
	}

	if (m_partitionData)
		m_partitionData->makeDirty();
	if (m_partitionManagerData)
		m_partitionManagerData->makeDirty();
	if (m_collisionManagerData)
		m_collisionManagerData->makeDirty();

	if (TheLuaScriptEngine)
	{
		TheLuaScriptEngine->UnRegisterObject(this);
		TheLuaScriptEngine->RegisterObject(this);
	}

	if (team)
	{
		ContainModuleInterface *contain = m_contain;
		if (contain)
		{
			HordeContainInterface *horde = contain->getHordeContainInterface();
			if (horde)
				horde->rva0046D384(team);
		}
		TheRadar->rva002D7FAE(this);
		updateUpgradeModules();
	}

	Drawable *draw = m_drawable;
	if (draw)
		draw->preloadAssets();
}

