// FUNCTION: BFME2 0x0028D2FB size=279 name=?setEffectivelyDead@Object@@QAEX_N@Z evidence=N:ledger tier=A
void Object::setEffectivelyDead(Bool dead)
{
	if (dead)
	{
		if (m_privateStatus & EFFECTIVELY_DEAD)
			return;
		m_privateStatus |= EFFECTIVELY_DEAD;

		if (m_radarData)
			TheRadar->removeObject(this);
		TheGameLogic->updateObjectsChangedTriggerAreas();
		TheScriptEngine->notifyOfObjectCreationOrDestruction();

		// A hero's HeroDie module runs as the hero becomes effectively dead, with no damage.
		if (getTemplate()->isKindOf(KINDOF_HERO))
		{
			static NameKeyType key_HeroDie = TheNameKeyGenerator->nameToKey("HeroDie");
			DieModule *die = (DieModule *)findModule(key_HeroDie);
			if (die)
				die->onDie(NULL);
		}

		Drawable *draw = m_drawable;
		if (draw)
		{
			for (Int buff = 1; buff < 9; ++buff)
				draw->turnOffBuff(buff, false);
		}
	}
	else
	{
		if (!(m_privateStatus & EFFECTIVELY_DEAD))
			return;
		m_privateStatus &= ~EFFECTIVELY_DEAD;

		if (!m_radarData)
			TheRadar->addObject(this);
		TheGameLogic->updateObjectsChangedTriggerAreas();
		TheScriptEngine->notifyOfObjectCreationOrDestruction();
		rva0028AD7C();
	}
}

