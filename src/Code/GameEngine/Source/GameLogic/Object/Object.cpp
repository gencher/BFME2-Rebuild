// FUNCTION: BFME2 0x002966A0 size=169 name=?onCapture@Object@@QAEXPAVPlayer@@0@Z evidence=N:ledger tier=A
void Object::onCapture(Player *oldOwner, Player *newOwner)
{
	// Everybody chills when they are captured so they don't keep doing something the new player might not want
	if (getAI() && oldOwner != newOwner)
		getAI()->aiIdle(CMD_FROM_AI);

	// this gets the new owner some points
	newOwner->getScoreKeeper()->addObjectCaptured(this);

	// rip through the behavior modules and call the onCapture for any modules that care
	for (BehaviorModule **module = m_behaviors; *module; ++module)
		(*module)->onCapture(oldOwner, newOwner);

	// We have to undo our look for the old team and redo it for the new.
	if (m_partitionData)
		m_partitionData->makeDirty();
	if (m_collisionManagerData)
		m_collisionManagerData->makeDirty();
	if (m_partitionManagerData)
		m_partitionManagerData->makeDirty();

	setScriptStatus((ObjectScriptStatusBit)4, false);	// Zero Hour's OBJECT_STATUS_SCRIPT_UNSELLABLE

	// mark the command bar to redraw
	if (oldOwner->isLocalPlayer() || newOwner->isLocalPlayer())
		TheControlBar->markUIDirty();
}

