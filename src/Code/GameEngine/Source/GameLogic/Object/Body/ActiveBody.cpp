// FUNCTION: BFME2 0x004BEE21 size=484 name=?attemptHealing@ActiveBody@@UAEXPAVDamageInfo@@@Z evidence=N:ledger tier=A
void ActiveBody::attemptHealing(DamageInfo *damageInfo)
{
	validateArmorAndDamageFX();
	const ActiveBodyModuleData *data = static_cast<const ActiveBodyModuleData *>(m_moduleData);
	Object *obj = m_object;
	if (data->m_burningDeathBehavior && obj->testModelConditionState((ModelConditionFlagType)0x220))
		return;
	if (!damageInfo)
		return;
	if (damageInfo->in.m_damageType != DAMAGE_HEALING)
	{
		attemptDamage(damageInfo);
		return;
	}
	if (!obj->getTemplate()->m_keepSelectableWhenDead && !obj->getTemplate()->isKindOf(KINDOF_WALL_UPGRADE)
		&& !obj->getTemplate()->isKindOf(KINDOF_BRIDGE) && !obj->getTemplate()->isKindOf(KINDOF_BRIDGE_TOWER)
		&& obj->isEffectivelyDead())
		return;
	damageInfo->out.m_actualDamageDealt = 0.0f;
	damageInfo->out.m_actualDamageClipped = 0.0f;
	Real healing = m_curArmor.adjustDamage(&damageInfo->in, getObject(), false);
	if (healing > 0.0f)
	{
		Int oldState = m_curDamageState;
		internalChangeHealth(healing, damageInfo);
		damageInfo->out.m_actualDamageDealt = healing;
		damageInfo->out.m_actualDamageClipped = m_prevHealth - m_currentHealth;
		m_lastHealingTimestamp = TheGameLogic->getFrame();
		if (m_currentHealth > m_prevHealth)
		{
			for (BehaviorModule **module = obj->getBehaviorModules(); *module; ++module)
			{
				DamageModuleInterface *damage = (*module)->getDamage();
				if (damage)
					damage->onHealing(damageInfo);
			}
			if (!obj->getTemplate()->isKindOf(KINDOF_STRUCTURE) && data->m_healingBuffFx && !obj->m_status.test(6))
				FXList::doFXObj(data->m_healingBuffFx, obj, 0);
			TheGameLogic->m_dotManager->rva0043B72D((Int)obj->getID());
		}
		if (m_curDamageState != oldState)
		{
			for (BehaviorModule **module = obj->getBehaviorModules(); *module; ++module)
			{
				DamageModuleInterface *damage = (*module)->getDamage();
				if (damage)
					damage->onBodyDamageStateChange(damageInfo, (BodyDamageType)oldState, (BodyDamageType)m_curDamageState);
			}
			if (m_unk0xEC)
			{
				Object *linked = TheGameLogic->findObjectByID(m_unk0xEC);
				if (linked && linked->getBodyModule())
					linked->getBodyModule()->rvaSlot39((BodyDamageType)m_curDamageState);
			}
		}
	}
	doDamageFX(damageInfo);
}

// FUNCTION: BFME2 0x004BF005 size=385 name=?internalChangeHealth@ActiveBody@@UAEXMPAVDamageInfo@@@Z evidence=N:ledger tier=A
void ActiveBody::internalChangeHealth(Real delta, DamageInfo *damageInfo)
{
	m_prevHealth = m_currentHealth;
	m_currentHealth += delta;

	Real maxHealth = m_maxHealth;
	if (m_currentHealth > maxHealth)
	{
		m_currentHealth = maxHealth;
		for (Int i = 0; i < 4; ++i)
			m_damageStateValues[i] = 0.0f;
	}
	else if (m_prevHealth == 0.0f)
	{
		Real value = getMaxHealth() * 0.25f;
		value = value * 0.75f - 1.0f;
		for (Int i = 0; i < 4; ++i)
			m_damageStateValues[i] = value;
	}
	else if (delta > 0.0f)
	{
		Real reduce = delta * 0.25f;
		reduce *= 0.75f;
		for (Int i = 0; i < 4; ++i)
		{
			m_damageStateValues[i] -= reduce;
			m_damageStateValues[i] = _STL::max(m_damageStateValues[i], 0.0f);
		}
	}

	if (m_currentHealth < 0.0f)
		m_currentHealth = 0.0f;

	Int oldState = m_curDamageState;
	Int oldSideDestroyed = m_bodySideDestroyed;
	setCorrectDamageState(false);

	Object *us = getObject();
	if (m_curDamageState != oldState || m_bodySideDestroyed != oldSideDestroyed)
	{
		if (m_currentHealth <= 0.0f || !us->testStatus(OBJECT_STATUS_UNDER_CONSTRUCTION))
			rvaSlot36();
	}

	us->setEffectivelyDead(m_currentHealth <= 0.0f);

	if (m_unk0xEC)
	{
		Object *other = TheGameLogic->findObjectByID(m_unk0xEC);
		if (other)
		{
			BodyModuleInterface *body = other->getBodyModule();
			if (body)
			{
				body->rvaSlot40(m_currentHealth, delta > 0.0f);
				other->m_constructionPercent = getObject()->m_constructionPercent;
			}
		}
	}
}

