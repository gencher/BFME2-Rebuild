// FUNCTION: BFME2 0x004BFB1C size=440 name=?rva004BFB1C@ActiveBody@@QAEXMPBVCoord3D@@@Z evidence=X:retail PE exports class Coord3D: ??0Matrix4D@@QAE@ABVCoord3D@@@Z tier=A
void ActiveBody::rva004BFB1C(Real amount, const Coord3D *position)
{
	const Matrix3D matrix = getObject()->m_transform;
	Vector3 forward = matrix.Get_X_Vector();
	Vector3 dir(matrix.Row[0][3] - position->x, matrix.Row[1][3] - position->y, matrix.Row[2][3] - position->z);
	Real sides[4];
	sides[0] = Vector3::Dot_Product(-forward, dir);
	sides[1] = Vector3::Dot_Product(matrix.Get_Y_Vector(), dir);
	sides[2] = -sides[0];
	sides[3] = -sides[1];

	_STL::vector<long> order;
	for (long i = 0; i < 4; ++i)
	{
		Bool inserted = false;
		for (_STL::vector<long>::iterator it = order.begin(); it != order.end(); ++it)
		{
			Int other = *it;
			if (sides[i] > sides[other])
			{
				order.insert(it, i);
				inserted = true;
				break;
			}
		}
		if (!inserted)
			order.push_back(i);
	}

	Real maxPerSide = getMaxHealth() * 0.25f;
	maxPerSide *= 0.75f;
	Real remaining = amount;
	for (Int k = 0; remaining > 0.0f; ++k)
	{
		if (k >= 4)
			break;
		Real &health = m_damageStateValues[order[k]];
		Real room = maxPerSide - health;
		Real take = _STL::min(remaining, room);
		if (take > 0.0f)
		{
			health = health + take;
			remaining -= take;
		}
	}
}

