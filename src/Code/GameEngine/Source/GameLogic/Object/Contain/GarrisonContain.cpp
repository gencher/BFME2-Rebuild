// FUNCTION: BFME2 0x00479292 size=170 name=?getObjectGarrisonPointIndex@GarrisonContain@@UAEHW4ObjectID@@@Z evidence=N:ledger tier=A
Int GarrisonContain::getObjectGarrisonPointIndex(ObjectID id)
{
	if (id == 0)
		return GARRISON_INDEX_INVALID;
	Object *obj = TheGameLogic->findObjectByID(id);
	if (obj == NULL)
		return GARRISON_INDEX_INVALID;
	for (Int i = 0; i < MAX_GARRISON_POINTS; ++i)
	{
		ContainModuleInterface *contain = obj->getContain();
		if (contain)
		{
			HordeContainInterface *horde = contain->getHordeContainInterface();
			if (horde)
			{
				ContainmentListView view = horde->hordeSlot66();
				const ContainedItemsList &units = view.objects();
				ContainedItemsList::const_iterator end = units.end();
				for (ContainedItemsList::const_iterator it = units.begin(); it != end; ++it)
				{
					Object *unit = *it;
					for (Int j = 0; j < MAX_GARRISON_POINTS; ++j)
					{
						if (m_garrisonPointData[j].objectID == unit->getID())
							return j;
					}
				}
			}
		}
		else if (m_garrisonPointData[i].objectID == id)
			return i;
	}
	return GARRISON_INDEX_INVALID;
}

