int GameWindow::winBringToTop()
{
	GameWindowManager *mgr = TheWindowManager;
	GameWindow *parent = m_parent;
	if (parent)
	{
		mgr->unlinkChildWindow(this);
		TheWindowManager->addWindowToParent(this, parent);
	}
	else
	{
		GameWindow *cur = mgr->winGetWindowList();
		while (cur != this)
		{
			if (!cur)
				return -3;
			cur = cur->m_next;
		}
		TheWindowManager->unlinkWindow(this);
		TheWindowManager->linkWindow(this);
	}
	WindowLayout *layout = m_layout;
	if (layout)
	{
		layout->removeWindow(this);
		layout->addWindow(this);
	}
	return 0;
}

