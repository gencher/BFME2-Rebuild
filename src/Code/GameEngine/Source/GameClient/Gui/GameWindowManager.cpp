// FUNCTION: BFME2 0x002C2533 size=263 name=?winCreate@GameWindowManager@@QAEPAVGameWindow@@PAURva0047EDE0CreateInfo@@@Z evidence=N:ledger

// FUNCTION: BFME2 0x002C263A size=1214 name=?gogoMessageBox@GameWindowManager@@UAEPAVGameWindow@@HHHHGVUnicodeString@@0P6AXXZ111_N@Z evidence=N:ledger

GameWindow *GameWindowManager::gogoMessageBox(Int x, Int y, Int width, Int height, UnsignedShort buttonFlags,
                        UnicodeString title, UnicodeString body,
                        GameWinMsgBoxFunc onYes,
                        GameWinMsgBoxFunc onNo,
                        GameWinMsgBoxFunc onOk,
                        GameWinMsgBoxFunc onCancel, Bool useLogo )

{
	if (buttonFlags == 0)
		return NULL;

	// The logo variant is a separate layout file with its own widget-name prefix.
	GameWindow *root = NULL;
	if (useLogo)
		root = this->winCreateFromScript(AsciiString("Menus/QuitMessageBox.wnd"), NULL, NULL);
	else
		root = this->winCreateFromScript(AsciiString("Menus/MessageBox.wnd"), NULL, NULL);
	root->m_callbackExtra = NULL;

	AsciiString prefix;
	if (useLogo)
		prefix.set("QuitMessageBox.wnd:");
	else
		prefix.set("MessageBox.wnd:");

	AsciiString widgetName;
	GameWindow *panel = NULL;

	widgetName = prefix;
	widgetName.concat("MessageBoxParent");
	panel = TheWindowManager->winGetWindowFromId(root, TheNameKeyGenerator->nameToKey(widgetName));
	if (panel != NULL)
		panel->m_callbackExtra = NULL;
	TheWindowManager->winSetModal(root);
	TheWindowManager->winSetFocus(NULL);
	TheWindowManager->winSetFocus(panel);

	float scaleX, scaleY = 1;

	// A requested size rescales the panel and every child by the same ratios.
	if (width > 0 && height > 0)
	{
		ICoord2D extent;
		panel->winGetSize(&extent.x, &extent.y);
		scaleX = (float)width / (float)extent.x;
		scaleY = (float)height / (float)extent.y;
		panel->winSetSize(width, height);

		GameWindow *widget;
		for (widget = panel->winGetChild(); widget; widget = widget->winGetNext())
		{
			widget->winGetSize(&extent.x, &extent.y);
			extent.x = Int(extent.x * scaleX);
			extent.y = Int(extent.y * scaleY);
			widget->winSetSize(extent.x, extent.y);

			widget->winGetPosition(&extent.x, &extent.y);
			extent.x = Int(extent.x * scaleX);
			extent.y = Int(extent.y * scaleY);
			widget->winSetPosition(extent.x, extent.y);
		}
	}

	if (x >= 0 && y >= 0)
		panel->winSetPosition(x, y);

	// Home positions of the three button slots, read from the layout's OK, No and Cancel buttons.
	Int slotX[3], slotY[3];

	NameKeyType okKey = NAMEKEY_INVALID;

	widgetName = prefix;
	widgetName.concat("ButtonOk");
	okKey = TheNameKeyGenerator->nameToKey(widgetName);
	GameWindow *okButton = TheWindowManager->winGetWindowFromId(panel, okKey);
	okButton->winGetPosition(&slotX[0], &slotY[0]);

	widgetName = prefix;
	widgetName.concat("ButtonYes");
	NameKeyType yesKey = TheNameKeyGenerator->nameToKey(widgetName);
	GameWindow *yesButton = TheWindowManager->winGetWindowFromId(panel, yesKey);
	widgetName = prefix;
	widgetName.concat("ButtonNo");
	NameKeyType noKey = TheNameKeyGenerator->nameToKey(widgetName);
	GameWindow *noButton = TheWindowManager->winGetWindowFromId(panel, noKey);
	noButton->winGetPosition(&slotX[1], &slotY[1]);

	widgetName = prefix;
	widgetName.concat("ButtonCancel");
	NameKeyType cancelKey = TheNameKeyGenerator->nameToKey(widgetName);
	GameWindow *cancelButton = TheWindowManager->winGetWindowFromId(panel, cancelKey);
	cancelButton->winGetPosition(&slotX[2], &slotY[2]);

	// OK or Yes takes the first slot; No and Cancel share the last two, or one of them takes the last.
	if ((buttonFlags & MSG_BOX_OK) == MSG_BOX_OK)
	{
		okButton->winSetPosition(slotX[0], slotY[0]);
		okButton->winHide(false);
	}
	else if ((buttonFlags & MSG_BOX_YES) == MSG_BOX_YES)
	{
		yesButton->winSetPosition(slotX[0], slotY[0]);
		yesButton->winHide(false);
	}

	if ((buttonFlags & (MSG_BOX_NO | MSG_BOX_CANCEL)) == (MSG_BOX_NO | MSG_BOX_CANCEL))
	{
		noButton->winSetPosition(slotX[1], slotY[1]);
		cancelButton->winSetPosition(slotX[2], slotY[2]);
		noButton->winHide(false);
		cancelButton->winHide(false);
	}
	else if ((buttonFlags & MSG_BOX_NO) == MSG_BOX_NO)
	{
		noButton->winSetPosition(slotX[2], slotY[2]);
		noButton->winHide(false);
	}
	else if ((buttonFlags & MSG_BOX_CANCEL) == MSG_BOX_CANCEL)
	{
		cancelButton->winSetPosition(slotX[2], slotY[2]);
		cancelButton->winHide(false);
	}

	widgetName = prefix;
	widgetName.concat("StaticTextTitle");
	NameKeyType titleKey = TheNameKeyGenerator->nameToKey(widgetName);
	GameWindow *titleText = TheWindowManager->winGetWindowFromId(panel, titleKey);
	GadgetStaticTextSetText(titleText, title);
	widgetName = prefix;
	widgetName.concat("StaticTextMessage");
	NameKeyType messageKey = TheNameKeyGenerator->nameToKey(widgetName);
	GameWindow *messageText = TheWindowManager->winGetWindowFromId(panel, messageKey);
	GadgetStaticTextSetText(messageText, body);

	WindowMessageBoxData *callbacks = new WindowMessageBoxData;
	callbacks->cancelCallback = onCancel;
	callbacks->noCallback = onNo;
	callbacks->okCallback = onOk;
	callbacks->yesCallback = onYes;
	root->winSetUserData(callbacks);

	panel->winHide(false);
	panel->winBringToTop();

	return root;
}

