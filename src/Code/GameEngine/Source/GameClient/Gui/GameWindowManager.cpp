// FUNCTION: BFME2 0x002C0ED5 size=147 name=?winSetFocus@GameWindowManager@@UAEHPAVGameWindow@@@Z evidence=N:ledger
int GameWindowManager::winSetFocus(GameWindow *window)
{
    bool wantsFocus=false;
    if (window && (window->winGetStatus() & 0x400)) return 0;
    if (m_keyboardFocus && m_keyboardFocus!=window) {
        bool wantsOldFocus;
        winSendSystemMsg(m_keyboardFocus,23,0,(unsigned int)&wantsOldFocus);
    }
    m_keyboardFocus=window;
    if(m_keyboardFocus) {
        for(;;) {
            winSendSystemMsg(window,23,1,(unsigned int)&wantsFocus);
            if(wantsFocus) break;
            window=window->winGetParent();
            if(!window) break;
        }
    }
    if(!wantsFocus) m_keyboardFocus=0;
    return 0;
}

// FUNCTION: BFME2 0x002C0F68 size=97 name=?rva002C0F68@GameWindowManager@@UAEH_N0@Z evidence=?:placeholder
WinInputReturnCode GameWindowManager::winProcessKey(unsigned char key, unsigned char state)
{
    int result = 0;
    GameWindow *next;
    GameWindow *current = m_keyboardFocus;
    if (!current) goto done;
    if (!key) goto done;
    next = current;
    {
        int stateValue = state;
        int keyValue = key;
        result = 1;
        goto tryParent;
    parent:
        next = next->winGetParent();
        if (!next) {
            result = 0;
            goto done;
        }
    tryParent:
        if (winSendInputMsg(next, 21, keyValue, stateValue)) goto done;
        else goto parent;
    }
done:
    return (WinInputReturnCode)result;
}

// FUNCTION: BFME2 0x002C0FC9 size=198 name=?drawWindow@GameWindowManager@@IAEHPAVGameWindow@@@Z evidence=N:ledger
int GameWindowManager::drawWindow(GameWindow *window)
{
	if (window == 0)
		return -2;
	if (!(window->m_status & 0x10)) {
		if (!(window->m_status & 0x10000)) {
			if (window->draw(&window->m_instData) != 1 && window->m_positionSink)
				window->m_positionSink->draw(window, &window->m_instData);
		}
		if ((window->winGetStyle() & 0x20) && (window->m_status & 0x1000) && !(window->m_status & 0x10000))
			window->winDrawBorder();
		GameWindow *child = window->m_child;
		while (child && child->m_next)
			child = child->m_next;
		for (; child; child = child->m_prev)
			drawWindow(child);
		if (!(window->winGetStyle() & 0x20) && (window->m_status & 0x1000) && !(window->m_status & 0x10000))
			window->winDrawBorder();
	}
	return 0;
}

