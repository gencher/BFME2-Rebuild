// FUNCTION: BFME2 0x0031DFD1 size=151 name=?GetPurchaseScienceStatus@ControlBar@@QAEXPAVPlayer@@HPAPBVCommandButton@@PA_N22@Z evidence=N:ledger tier=A
void ControlBar::GetPurchaseScienceStatus(Player *player, int index, const CommandButton **buttonOut, bool *found, bool *canPurchase, bool *hasScience)
{
	*found = false;
	*canPurchase = false;
	*hasScience = false;

	const CommandSet *set = getPurchaseScienceCommandSet(player);
	if (!set)
		return;
	*buttonOut = set->getCommandButton(index);
	if (!*buttonOut)
		return;
	*found = true;

	const CommandButton *button = *buttonOut;
	if (button->getScienceVec().empty())
		return;
	ScienceType science = button->getScienceVec()[0];

	// Retail hands both ScienceStore predicates the player's ScienceQueryInterface (Player + 4, null stays null);
	// playerHasRootPrereqsForScience is declared against the Player spelling of that argument.
	ScienceQueryInterface *holder = player;
	if (!TheScienceStore->playerHasRootPrereqsForScience(reinterpret_cast<const Player *>(holder), science))
		return;
	if (!player->hasScience(science)) {
		if (TheScienceStore->rva001FF4D3(holder, science))
			*canPurchase = true;
	} else {
		*hasScience = true;
	}
}

// FUNCTION: BFME2 0x0031E068 size=54 name=?rva0031E068@ControlBar@@QAE_NPAVPlayer@@H@Z evidence=?:placeholder tier=A
bool ControlBar::rva0031E068(Player *player, int science)
{
	const CommandButton *button;
	bool canPurchase;
	bool hasPrerequisites;
	bool alreadyOwned;
	GetPurchaseScienceStatus(player, science, &button, &canPurchase, &hasPrerequisites, &alreadyOwned);
	return canPurchase && hasPrerequisites && !alreadyOwned;
}

