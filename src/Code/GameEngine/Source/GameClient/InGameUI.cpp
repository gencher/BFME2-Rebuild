bool InGameUI::removeSuperweapon(int playerIndex, const AsciiString &powerName, ObjectID id, const SpecialPowerTemplate *powerTemplate)
{
	_STL::map<AsciiString, _STL::list<SuperweaponInfo *> >::iterator mapIt = m_superweapons[playerIndex].find(powerName);
	if (mapIt != m_superweapons[playerIndex].end())
	{
		_STL::list<SuperweaponInfo *> &swList = mapIt->second;
		for (_STL::list<SuperweaponInfo *>::iterator listIt = swList.begin(); listIt != swList.end(); ++listIt)
		{
			if ((*listIt)->m_objectID == id)
			{
				SuperweaponInfo *info = *listIt;
				swList.erase(listIt);
				::delete info;
				if (swList.size() == 0)
					m_superweapons[playerIndex].erase(mapIt);
				return true;
			}
		}
	}
	return false;
}

