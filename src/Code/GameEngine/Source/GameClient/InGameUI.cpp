// FUNCTION: BFME2 0x002A43A0 size=309 name=?objectChangedTeam@InGameUI@@UAEXPBVObject@@HH@Z evidence=N:ledger tier=A
void InGameUI::objectChangedTeam(const Object *obj, int oldPlayerIndex, int newPlayerIndex)
{
	// nothing to move without an object and two real owners
	if (obj == NULL || oldPlayerIndex < 0 || newPlayerIndex < 0)
		return;

	ObjectID changedID = obj->getID();
	AsciiString timerName;
	for (BehaviorModule **module = obj->getBehaviorModules(); *module != NULL; ++module)
	{
		SpecialPowerModuleInterface *spModule = (*module)->getSpecialPower();
		if (spModule == NULL)
			continue;

		const SpecialPowerTemplate *spTmpl = spModule->getSpecialPowerTemplate();
		timerName = spTmpl->getName();
		// is this power's timer already listed under the old owner?
		bool listed = false;
		_STL::map<AsciiString, _STL::list<SuperweaponInfo *> >::iterator byName = m_superweapons[oldPlayerIndex].find(timerName);
		if (byName != m_superweapons[oldPlayerIndex].end())
		{
			_STL::list<SuperweaponInfo *> &timers = byName->second;
			for (_STL::list<SuperweaponInfo *>::iterator entry = timers.begin(); entry != timers.end(); ++entry)
			{
				if ((*entry)->m_objectID == changedID)
				{
					listed = true;
					break;
				}
			}
		}

		if (listed)
		{
			// the timer follows the object to its new owner
			removeSuperweapon(oldPlayerIndex, timerName, changedID, spTmpl);
			addSuperweapon(newPlayerIndex, timerName, changedID, spTmpl);
		}
		else if (TheGameLogic->getFrame() == 0
			&& !obj->testStatus(OBJECT_STATUS_UNDER_CONSTRUCTION)
			&& !obj->getTemplate()->isKindOf(KINDOF_COMMANDCENTER))
		{
			addSuperweapon(newPlayerIndex, timerName, changedID, spTmpl);
		}
	}
}

