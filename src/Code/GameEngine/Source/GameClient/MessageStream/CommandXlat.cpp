// FUNCTION: BFME2 0x00429CBB size=342 name=?evaluateForceAttack@CommandTranslator@@AAEHPAVDrawable@@PBUCoord3D@@W4CommandEvaluateType@@@Z evidence=N:ledger
int CommandTranslator::evaluateForceAttack(Drawable *draw, const Coord3D *pos, CommandEvaluateType type)
{
	int retVal = GameMessage::MSG_INVALID;
	if (!draw && !pos)
		return retVal;

	const DrawableList *allSelected = TheInGameUI->getAllSelectedDrawables();

	if (draw)
	{
		Object *obj = draw->getObject();
		if (!obj)
			return retVal;

		Int result = canAnyForceAttack(allSelected, obj, pos);
		if (result == ATTACKRESULT_POSSIBLE || result == ATTACKRESULT_POSSIBLE_AFTER_MOVING)
		{
			retVal = GameMessage::MSG_DO_FORCE_ATTACK_OBJECT;
			if (type == DO_COMMAND)
			{
				PickAndPlayInfo info;
				info.m_drawTarget = draw;
				pickAndPlayUnitVoiceResponse(allSelected, (GameMessage::Type)retVal, &info);
				GameMessage *newMsg = TheMessageStream->appendMessage((GameMessage::Type)retVal);
				newMsg->appendObjectIDArgument(obj->getID());
				newMsg->appendLocationArgument(*pos);
			}
			else if (type == DO_HINT)
			{
				retVal = GameMessage::MSG_DO_FORCE_ATTACK_OBJECT_HINT;
				TheMessageStream->appendMessage((GameMessage::Type)retVal);
			}
		}
		else if (result == ATTACKRESULT_INVALID_SHOT && type == DO_HINT)
		{
			retVal = GameMessage::MSG_IMPOSSIBLE_ATTACK_HINT;
			TheMessageStream->appendMessage((GameMessage::Type)retVal);
		}
	}
	else if (pos)
	{
		Int result = canAnyForceAttack(allSelected, 0, pos);
		if (result == ATTACKRESULT_POSSIBLE || result == ATTACKRESULT_POSSIBLE_AFTER_MOVING)
		{
			retVal = GameMessage::MSG_DO_FORCE_ATTACK_GROUND;
			if (type == DO_COMMAND)
			{
				PickAndPlayInfo info;
				info.m_position = *pos;
				pickAndPlayUnitVoiceResponse(allSelected, (GameMessage::Type)retVal, &info);
				GameMessage *newMsg = TheMessageStream->appendMessage((GameMessage::Type)retVal);
				newMsg->appendLocationArgument(*pos);
			}
			else if (type == DO_HINT)
			{
				retVal = GameMessage::MSG_DO_FORCE_ATTACK_GROUND_HINT;
				TheMessageStream->appendMessage((GameMessage::Type)retVal);
			}
		}
		else if (result == ATTACKRESULT_INVALID_SHOT && type == DO_HINT)
		{
			retVal = GameMessage::MSG_IMPOSSIBLE_ATTACK_HINT;
			TheMessageStream->appendMessage((GameMessage::Type)retVal);
		}
	}

	return retVal;
}

