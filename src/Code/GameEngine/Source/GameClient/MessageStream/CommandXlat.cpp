int CommandTranslator::createAttackMessage(Drawable *draw, Drawable *other, int commandType)
{
	// the drawable must have an object to be able to attack
	if (draw->getObject() == 0)
		return 0;

	// the target must have an object to be attacked
	if (other->getObject() == 0)
		return 0;

	// only make the message if we are really doing a command
	if (commandType == DO_COMMAND)
	{
		GameMessage *attackmsg = TheMessageStream->appendMessage(GameMessage::MSG_DO_ATTACK_OBJECT);
		attackmsg->appendObjectIDArgument(other->getObject()->getID());	// must pass object IDs to logic

		// flash the attacked drawable, or the horde that contains it
		Drawable *target = other;
		Object *container = other->getObject()->getContainedBy();
		if (container && container->getTemplate()->isKindOf(KINDOF_HORDE))
			target = container->getDrawable();
		if (target)
			target->flashAsSelected(0);
	}

	return GameMessage::MSG_DO_ATTACK_OBJECT;
}

