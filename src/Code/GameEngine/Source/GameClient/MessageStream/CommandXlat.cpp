// FUNCTION: BFME2 0x004297F0 size=349 name=?issueAttackCommand@CommandTranslator@@AAEHPAVDrawable@@PBUCoord3D@@HH@Z evidence=N:ledger
int CommandTranslator::issueAttackCommand(Drawable *target, const Coord3D *pos, int commandType, int command)
{
	int msgType = GameMessage::MSG_INVALID;

	// sanity
	if (!target)
		return msgType;
	Object *targetObj = target->getObject();
	if (!targetObj)
		return msgType;

	if (m_teamExists)
	{
		// a GUI command in progress takes the click
		if (command != 0)
			return msgType;

		msgType = GameMessage::MSG_DO_ATTACK_OBJECT;
		if (commandType == DO_COMMAND)
		{
			GameMessage *attackMsg = TheMessageStream->appendMessage((GameMessage::Type)msgType);
			Coord3D attackPos;
			attackPos.zero();
			if (pos)
				attackPos = *pos;
			attackMsg->appendObjectIDArgument(targetObj->getID());
			attackMsg->appendLocationArgument(attackPos);

			// flash the attacked drawable, or the horde that contains it
			Drawable *draw = target;
			Object *container = targetObj->getContainedBy();
			if (container && container->getTemplate()->isKindOf(KINDOF_HORDE))
				draw = container->getDrawable();
			if (draw)
				draw->flashAsSelected(0);

			if (TheStatsCollector)
				TheStatsCollector->incrementAttackCount();
		}
	}
	else
	{
		const DrawableList *selected = TheInGameUI->getAllSelectedDrawables();
		for (DrawableList::const_iterator it = selected->begin(); it != selected->end(); ++it)
		{
			Drawable *draw = *it;
			msgType = createAttackMessage(draw, target, commandType);
		}
	}

	// only make sounds if we really did the command messages
	if (commandType == DO_COMMAND)
	{
		PickAndPlayInfo info;
		info.m_unk0x00 = targetObj->isUsingAirborneLocomotor();
		info.m_drawTarget = target;
		if (pos)
			info.m_position = *pos;
		else
			info.m_position = *target->getPosition();
		pickAndPlayUnitVoiceResponse(TheInGameUI->getAllSelectedDrawables(), (GameMessage::Type)msgType, &info);
	}

	return msgType;
}

