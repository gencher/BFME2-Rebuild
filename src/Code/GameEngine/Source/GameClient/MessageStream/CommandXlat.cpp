static Int canObjectForceAttack(Object *obj, const Object *victim, const Coord3D *pos)
{
	if (!obj->isAbleToAttack())
		return ATTACKRESULT_NOT_POSSIBLE;

	if (victim)
	{
		Int result = obj->getAbleToAttackSpecificObject((AbleToAttackType)1, victim, CMD_FROM_PLAYER);

		// objects whose spawns are the weapons ask the slave closest to the victim
		if (result != ATTACKRESULT_POSSIBLE && result != ATTACKRESULT_POSSIBLE_AFTER_MOVING
			&& obj->isKindOf(KINDOF_SPAWNS_ARE_THE_WEAPONS))
		{
			SpawnBehaviorInterface *spawnInterface = obj->getSpawnBehaviorInterface();
			if (spawnInterface)
			{
				Object *slave = spawnInterface->getClosestSlave(victim->getPosition());
				if (slave)
					result = slave->getAbleToAttackSpecificObject((AbleToAttackType)1, victim, CMD_FROM_PLAYER);
			}
		}
		return result;
	}

	if (pos)
	{
		if (obj->isKindOf(KINDOF_IMMOBILE) || obj->isKindOf(KINDOF_SPAWNS_ARE_THE_WEAPONS))
		{
			SpawnBehaviorInterface *spawnInterface = obj->getSpawnBehaviorInterface();
			if (spawnInterface)
				spawnInterface->getClosestSlave(pos);
		}
		return obj->getAbleToUseWeaponAgainstTarget((AbleToAttackType)0, 0, pos, CMD_FROM_PLAYER);
	}
	return ATTACKRESULT_NOT_POSSIBLE;
}

