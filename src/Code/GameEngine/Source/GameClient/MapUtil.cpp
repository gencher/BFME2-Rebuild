// FUNCTION: BFME2 0x0030469E size=166 name=?clearUnseenMaps@MapCache@@AAE_NVAsciiString@@@Z evidence=N:ledger
bool MapCache::clearUnseenMaps(AsciiString dirName)
{
    dirName.toLower();
    bool erasedSomething = false;
    _STL::map<AsciiString, bool>::iterator it = m_seen.begin();
    while (it != m_seen.end()) {
        AsciiString mapName = it->first;
        if (!it->second) {
            if (mapName.startsWithNoCase(dirName.str())) {
                erase(mapName);
                erasedSomething = true;
            }
        }
        ++it;
    }
    return erasedSomething;
}

