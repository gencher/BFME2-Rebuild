// FUNCTION: BFME2 0x00595D2D size=104 name=?behaviorDetectionUpdate@FirewallHelperClass@@QAE_NXZ evidence=N:ledger tier=B hypothesis:K
Bool FirewallHelperClass::behaviorDetectionUpdate()
{
	if (m_currentState == 0)
		return false;
	if (m_currentState != 9)
	{
		if (m_currentState == 1)
			{ Bool stepDone = detectionBeginUpdate(); return stepDone; }
		if (m_currentState == 2)
			{ Bool stepDone = detectionTest1Update(); return stepDone; }
		if (m_currentState == 3)
			{ Bool stepDone = detectionTest2Update(); return stepDone; }
		if (m_currentState == 4)
			{ Bool stepDone = detectionTest3Update(); return stepDone; }
		if (m_currentState == 5)
			{ Bool stepDone = detectionTest3WaitForResponsesUpdate(); return stepDone; }
		if (m_currentState == 6)
			{ Bool stepDone = detectionTest4Stage1Update(); return stepDone; }
		if (m_currentState == 7)
			{ Bool stepDone = detectionTest4Stage2Update(); return stepDone; }
		if (m_currentState == 8)
			m_currentState = 9;
	}
	return true;
}

// FUNCTION: BFME2 0x00595D95 size=177 name=?rva00595D95@Rva00595D95@@QAE_NXZ evidence=?:placeholder tier=B hypothesis:Z
Bool FirewallHelperClass::readFirewallBehavior()
{
	OptionPreferences pref;
	OptionPreferences::const_iterator it = pref.find(AsciiString("FirewallNeedToRefresh"));
	if (it != pref.end()) {
		AsciiString val = it->second;
		if (val.compareNoCase("TRUE") == 0)
			TheWritableGlobalData->m_firewallBehavior = 0;
	}
	if (TheWritableGlobalData->m_firewallBehavior == 0) {
		m_behavior = 1;
		m_currentState = 1;
		return false;
	}
	return true;
}

