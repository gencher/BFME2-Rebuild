void StatsCollector::collectMsgStats(const GameMessage *msg)
{
	if( ThePlayerList->m_local->getPlayerIndex() != msg->getPlayerIndex() )
		return;

	switch( msg->getType() )
	{
		case 0x417:
		case 0x419:
		case 0x463:
			++m_buildCommands;
			break;
	}
}

