// FUNCTION: BFME2 0x00437921 size=556 name=?writeStatInfo@StatsCollector@@AAEXXZ evidence=N:ledger
void StatsCollector::writeStatInfo()
{
	UnicodeString fileName(m_statsFileName);
	FILE *f = _wfopen(fileName.str(), L"a");
	if (!f)
		return;

	Player *player = ThePlayerList->getLocalPlayer();
	fprintf(f, "%d\t", m_timeCount);
	fprintf(f, "%.1f\t", TheDisplay ? TheDisplay->getAverageFPS() : 0.0f);
	fprintf(f, "%.1f\t", TheGameEngine ? TheGameEngine->m_instantNetFPS : 0.0f);
	fprintf(f, "%d\t", m_buildCommands);
	fprintf(f, "%d\t", m_moveCommands);
	fprintf(f, "%d\t", m_attackCommands);
	fprintf(f, "%d\t", m_scrollMapCommands);
	fprintf(f, "%d\t", m_scrollTime / BfmeLogicFramesPerSecond);
	fprintf(f, "%d\t", 0);
	fprintf(f, "%d\t", player->getMoney()->countMoney());
	fprintf(f, "%d\t", m_moneyWithdrawn);
	fprintf(f, "%d\t", m_moneyDeposited);
	fprintf(f, "%d\t", m_playerUnits);
	fprintf(f, "%d\t", m_aiUnits);
	fprintf(f, "%d\t", m_alliesKilled);
	fprintf(f, "%d\t", m_enemiesKilled);
	fprintf(f, "%d\t", m_neutralsKilled);

	Player *scorePlayer = ThePlayerList->getLocalPlayer();
	if (scorePlayer)
	{
		ScoreKeeper *keeper = scorePlayer->getScoreKeeper();
		if (keeper)
		{
			fprintf(f, "%d\t", keeper->getTotalMoneySpent() - m_scoreKeeperMoneySpent);
			fprintf(f, "%d\t", keeper->getTotalMoneyEarned() - m_scoreKeeperMoneyEarned);
			fprintf(f, "%d\t", keeper->getTotalUnitsDestroyed() - m_scoreKeeperUnitsDestroyed);
			fprintf(f, "%d\t", keeper->getTotalUnitsBuilt() - m_scoreKeeperUnitsBuilt);
			fprintf(f, "%d\t", keeper->getTotalUnitsLost() - m_scoreKeeperUnitsLost);
			fprintf(f, "%d\t", keeper->getTotalBuildingsDestroyed() - m_scoreKeeperBuildingsDestroyed);
			fprintf(f, "%d\t", keeper->getTotalBuildingsBuilt() - m_scoreKeeperBuildingsBuilt);
			fprintf(f, "%d\t", keeper->getTotalBuildingsLost() - m_scoreKeeperBuildingsLost);
		}
	}
	fprintf(f, "\n");
	fclose(f);
}

// FUNCTION: BFME2 0x00437B4D size=105 name=?collectUnitCountStats@StatsCollector@@QAEXXZ evidence=N:ledger
void StatsCollector::collectUnitCountStats()
{
	for (Object *obj = TheGameLogic->getFirstObject(); obj; obj = obj->getNextObject())
	{
		if (!(obj->isKindOf(KINDOF_INFANTRY) || obj->isKindOf(KINDOF_CAVALRY)) || obj->isNeutralControlled())
			continue;

		if (obj->getControllingPlayer()->getSide().compare("Civilian") == 0)
			continue;

		if (obj->getControllingPlayer()->isLocalPlayer())
			++m_playerUnits;
		else
			++m_aiUnits;
	}
}

// FUNCTION: BFME2 0x00437BB6 size=119 name=?update@StatsCollector@@QAEXXZ evidence=N:ledger
void StatsCollector::update()
{
    if(m_lastUpdate + (TheWritableGlobalData->m_playStats * ((unsigned int)BfmeLogicFramesPerSecond)) > static_cast<GameLogic *>(TheGameLogic)->getFrame()) return;
    collectUnitCountStats();
    if(m_isScrolling)
    {
        m_scrollTime += static_cast<GameLogic *>(TheGameLogic)->getFrame() - m_scrollBeginTime;
        m_scrollBeginTime = static_cast<GameLogic *>(TheGameLogic)->getFrame();
    }
    m_timeCount += TheWritableGlobalData->m_playStats;
    writeStatInfo();
    zeroOutStats(); collectScoreKeeperStats();
    m_lastUpdate = static_cast<GameLogic *>(TheGameLogic)->getFrame();
}

// FUNCTION: BFME2 0x00437C2D size=210 name=?writeFileEnd@StatsCollector@@QAEXXZ evidence=N:ledger
void StatsCollector::writeFileEnd()
{
	UnicodeString fileName(m_statsFileName);
	FILE *fILE = _wfopen(fileName.str(), L"a");
	if (!fILE)
		return;

	m_timeCount += (TheGameLogic->getFrame() - m_lastUpdate) / BfmeLogicFramesPerSecond;
	writeStatInfo();
	fprintf(fILE, "---------------------------------------------------\n");

	time_t aclock;
	time(&aclock);
	struct tm *newTime = localtime(&aclock);
	fprintf(fILE, "End Time:\t%s\n", asctime(newTime));
	fprintf(fILE, "* Times are in Game Seconds which are based on logic FPS: current logic FPS is %d, max update FPS (game speed) is %d\n",
		BfmeLogicFramesPerSecond, TheGameEngine->getFramesPerSecondLimit());

	fclose(fILE);
}

// FUNCTION: BFME2 0x00437CFF size=249 name=?createFileName@StatsCollector@@AAEXXZ evidence=N:ledger
void StatsCollector::createFileName()
{
	m_statsFileName.clear();
	char datestr[256] = "";
	time_t longTime;
	struct tm *curtime;
	time(&longTime);
	curtime = localtime(&longTime);
	strftime(datestr, 256, "_%b%d_%I%M%p", curtime);
	AsciiString name = TheWritableGlobalData->m_mapName;
	const char *fname = name.reverseFind('\\');
	if (fname)
		name.set(fname + 1);
	name.removeLastChar();
	name.removeLastChar();
	name.removeLastChar();
	name.removeLastChar();
	m_statsFileName.clear();
	m_statsFileName.format("%s%s%s.txt", statsDir, name.str(), datestr);
}

