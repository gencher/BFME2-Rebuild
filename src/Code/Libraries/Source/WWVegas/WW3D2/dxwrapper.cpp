// FUNCTION: BFME2 0x00122DF0 size=168 name=?Flip_To_Primary@DXWrapper@@SAXXZ evidence=N:ledger tier=A
// The device's TestCooperativeLevel is slot 3 (+0x0C), Present slot 17 (+0x44).
typedef HRESULT(__stdcall *DX8Wrapper_TestCooperativeLevelFn)(IDirect3DDevice9 *);
typedef HRESULT(__stdcall *DX8Wrapper_PresentFn)(IDirect3DDevice9 *, const RECT *, const RECT *, HWND, const RGNDATA *);

void DXWrapper::Flip_To_Primary(void)
{
	// If we are fullscreen and the current frame is odd then we need to force a page flip to ensure that the first
	// buffer in the flipping chain is the one visible.
	if (!IsWindowed) {
		int numBuffers = (_PresentParameters.BackBufferCount + 1);
		int visibleBuffer = (FrameCount % numBuffers);
		int flipCount = ((numBuffers - visibleBuffer) % numBuffers);
		int resetAttempts = 0;

		while ((flipCount > 0) && (resetAttempts < 3)) {
			HRESULT hr = ((*(DX8Wrapper_TestCooperativeLevelFn **)D3DDevice)[3])(D3DDevice);

			if (FAILED(hr)) {
				if (D3DERR_DEVICELOST == hr) {
					IsDeviceLost = true;
					return;
				}
				IsDeviceLost = false;

				if (D3DERR_DEVICENOTRESET == hr) {
					Reset_Device();
					resetAttempts++;
				}
			} else {
				hr = ((*(DX8Wrapper_PresentFn **)D3DDevice)[17])(D3DDevice, NULL, NULL, NULL, NULL);

				if (SUCCEEDED(hr)) {
					IsDeviceLost = false;
					FrameCount++;
				} else {
					IsDeviceLost = true;
				}
			}

			--flipCount;
		}
	}
}

