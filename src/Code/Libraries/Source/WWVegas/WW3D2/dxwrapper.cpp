// FUNCTION: BFME2 0x00120CD0 size=629 name=?Set_Projection_Transform_With_Z_Bias@DXWrapper@@SAXABVMatrix4x4@@MM@Z evidence=N:ledger tier=A
void DXWrapper::Set_Projection_Transform_With_Z_Bias(const Matrix4x4 &matrix, float znear, float zfar)
{
	ZFar = zfar;
	ZNear = znear;
	ProjectionMatrix = matrix.Transpose();
	// Keep the unbiased transpose for subsequent depth-bias updates.
	DeviceProjectionMatrix = ProjectionMatrix;
	if (ZNear != ZFar) {
		float scale = ZNear * ZFar / (ZFar - ZNear);
		float bias = ZBias * 0.000625f;
		DeviceProjectionMatrix[3][2] -= scale * bias;
	}
	DX8_SET_TRANSFORM(_Get_D3D_Device8(), D3DTS_PROJECTION, &DeviceProjectionMatrix);
	number_of_DX8_calls++;
}

