// Find the resolution mode with at least resx,resy with the highest supported refresh rate.
bool DXWrapper::Find_Color_Mode(D3DFORMAT colorbuffer, int resx, int resy, UINT *mode)
{
	UINT i, j, modemax;
	UINT rx, ry;
	D3DDISPLAYMODE dmode;
	::ZeroMemory(&dmode, sizeof(D3DDISPLAYMODE));

	rx = (unsigned int)resx;
	ry = (unsigned int)resy;

	bool found = false;
	modemax = ((*(DX8Wrapper_GetAdapterModeCountFn **)D3DInterface)[6])(D3DInterface, D3DADAPTER_DEFAULT, colorbuffer);
	i = 0;

	while (i < modemax && !found) {
		((*(DX8Wrapper_EnumAdapterModesFn **)D3DInterface)[7])(D3DInterface, D3DADAPTER_DEFAULT, colorbuffer, i, &dmode);
		if (dmode.Width == rx && dmode.Height == ry && dmode.Format == colorbuffer) {
			found = true;
		}
		i++;
	}
	i--;	// this is the first valid mode

	// no match
	if (!found) {
		return false;
	}

	// go to the highest refresh rate in this mode
	bool stillok = true;
	j = i;
	while (j < modemax && stillok) {
		((*(DX8Wrapper_EnumAdapterModesFn **)D3DInterface)[7])(D3DInterface, D3DADAPTER_DEFAULT, colorbuffer, j, &dmode);
		if (dmode.Width == rx && dmode.Height == ry && dmode.Format == colorbuffer) {
			stillok = true;
		} else {
			stillok = false;
		}
		j++;
	}

	if (stillok == false) {
		*mode = j - 2;
	} else {
		*mode = i;
	}

	return true;
}

