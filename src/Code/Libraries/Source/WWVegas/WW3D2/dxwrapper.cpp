// FUNCTION: BFME2 0x00120980 size=519 name=?Set_Gamma@DXWrapper@@SAXMMM_N0@Z evidence=N:ledger tier=A
typedef HRESULT(__stdcall *DX8Wrapper_SetGammaRampFn)(IDirect3DDevice9 *, UINT, DWORD, const D3DGAMMARAMP *);	// slot 21 (+0x54)

void DXWrapper::Set_Gamma(float gamma, float bright, float contrast, bool calibrate, bool uselimit)
{
	gamma = Bound(gamma, 0.6f, 6.0f);
	bright = Bound(bright, -0.5f, 0.5f);
	contrast = Bound(contrast, 0.5f, 2.0f);
	float oo_gamma = 1.0f / gamma;

	number_of_DX8_calls++;

	DWORD flag = (calibrate ? D3DSGR_CALIBRATE : D3DSGR_NO_CALIBRATION);

	D3DGAMMARAMP ramp;
	float limit;

	if (uselimit) {
		limit = (contrast - 1) / 2 * contrast;
	} else {
		limit = 0.0f;
	}

	for (int i = 0; i < 256; i++) {
		float in, out;
		in = i / 256.0f;
		float x = in - limit;
		x = Bound(x, 0.0f, 1.0f);
		x = powf(x, oo_gamma);
		out = contrast * x + bright;
		out = Bound(out, 0.0f, 1.0f);
		ramp.red[i] = (WORD)(out * 65535);
		ramp.green[i] = (WORD)(out * 65535);
		ramp.blue[i] = (WORD)(out * 65535);
	}

	if (Get_Current_Caps()->Support_Gamma()) {
		((*(DX8Wrapper_SetGammaRampFn **)D3DDevice)[21])(D3DDevice, 0, flag, &ramp);
	} else {
		HWND hwnd = GetDesktopWindow();
		HDC hdc = GetDC(hwnd);
		if (hdc) {
			SetDeviceGammaRamp(hdc, &ramp);
			ReleaseDC(hwnd, hdc);
		}
	}
}

