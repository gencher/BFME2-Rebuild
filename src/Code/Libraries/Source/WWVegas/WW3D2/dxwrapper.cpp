// FUNCTION: BFME2 0x00125A80 size=468 name=?Registry_Load_Render_Device@DXWrapper@@SA_NPBD_N@Z evidence=N:ledger tier=B hypothesis:K
bool DXWrapper::Registry_Load_Render_Device(const char *sub_key, bool resize_window)
{
	char name[200];
	int width, height, depth, windowed;

	if (Registry_Load_Render_Device(sub_key, name, sizeof(name), width, height, depth, windowed, TextureBitDepth) &&
		(*name != 0)) {
		if (TextureBitDepth == 16 || TextureBitDepth == 32) {
		} else {
			TextureBitDepth = 16;
		}

		if (Set_Render_Device(name, width, height, depth, windowed, resize_window) != true) {
			if (depth == 16) depth = 32;
			else depth = 16;

			if (Set_Render_Device(name, width, height, depth, windowed, resize_window) == true) {
				return true;
			}

			if (depth == 16) depth = 32;
			else depth = 16;

			// We'll test resolutions down, so if the start is 640, increase to begin with...
			if (width == 640) {
				width = 1024;
				height = 768;
			}

			for (;;) {
				if (width > 2048) {
					width = 2048;
					height = 1536;
				} else if (width > 1920) {
					width = 1920;
					height = 1440;
				} else if (width > 1600) {
					width = 1600;
					height = 1200;
				} else if (width > 1280) {
					width = 1280;
					height = 1024;
				} else if (width > 1024) {
					width = 1024;
					height = 768;
				} else if (width > 800) {
					width = 800;
					height = 600;
				} else if (width != 640) {
					width = 640;
					height = 480;
				} else {
					return Set_Any_Render_Device();
				}

				for (int i = 0; i < 2; ++i) {
					if (Set_Render_Device(name, width, height, depth, windowed, resize_window) == true) {
						return true;
					}
					if (depth == 16) depth = 32;
					else depth = 16;
				}
			}
		}
		return true;
	}

	return Set_Any_Render_Device();
}

