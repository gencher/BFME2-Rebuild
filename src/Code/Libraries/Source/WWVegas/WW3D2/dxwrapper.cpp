// FUNCTION: BFME2 0x00124FF0 size=992 name=?Set_Render_Device@DXWrapper@@KA_NHHHHH_N00@Z evidence=N:ledger tier=A
bool DXWrapper::Set_Render_Device(int dev, int width, int height, int bits, int windowed,
	bool resize_window, bool reset_device, bool restore_assets)
{
	if (CurRenderDevice == -1 && dev == -1) {
		CurRenderDevice = 0;
	} else if (dev != -1) {
		CurRenderDevice = dev;
	}
	if (CurRenderDevice < 0 || CurRenderDevice >= _RenderDeviceNameTable.Count()) {
		return false;
	}

	if (width != -1)
		ResolutionWidth = width;
	if (height != -1)
		ResolutionHeight = height;
	if (bits != -1)
		BitDepth = bits;
	if (windowed != -1)
		IsWindowed = windowed != 0;
	DX8Wrapper_IsWindowed = IsWindowed;

	if (resize_window) {
		RECT rect = { 0 };
		::GetClientRect(_Hwnd, &rect);
		if (rect.right - rect.left != ResolutionWidth ||
		    rect.bottom - rect.top != ResolutionHeight) {
			rect.left = 0;
			rect.top = 0;
			rect.right = ResolutionWidth;
			rect.bottom = ResolutionHeight;
			DWORD style = ::GetWindowLong(_Hwnd, GWL_STYLE);
			::AdjustWindowRect(&rect, style, FALSE);

			if (!windowed) {
				::SetWindowPos(_Hwnd, HWND_TOPMOST, 0, 0, rect.right - rect.left,
					rect.bottom - rect.top, SWP_NOSIZE | SWP_NOMOVE);
			} else {
				::SetWindowPos(_Hwnd, NULL, 0, 0, rect.right - rect.left,
					rect.bottom - rect.top, SWP_NOZORDER | SWP_NOMOVE);
			}
		}
	}

	::ZeroMemory(&_PresentParameters, sizeof(_PresentParameters));
	_PresentParameters.BackBufferWidth = ResolutionWidth;
	_PresentParameters.BackBufferHeight = ResolutionHeight;
	_PresentParameters.BackBufferCount = IsWindowed ? 1 : 2;
	_PresentParameters.MultiSampleType = D3DMULTISAMPLE_NONE;
	_PresentParameters.SwapEffect = IsWindowed ? D3DSWAPEFFECT_DISCARD : D3DSWAPEFFECT_FLIP;
	_PresentParameters.hDeviceWindow = _Hwnd;
	_PresentParameters.Windowed = IsWindowed;
	_PresentParameters.EnableAutoDepthStencil = TRUE;
	_PresentParameters.Flags = 0;
	_PresentParameters.PresentationInterval = D3DPRESENT_INTERVAL_DEFAULT;
	_PresentParameters.FullScreen_RefreshRateInHz = D3DPRESENT_RATE_DEFAULT;

	if (IsWindowed) {
		D3DDISPLAYMODE desktop_mode;
		::ZeroMemory(&desktop_mode, sizeof(desktop_mode));
		D3DInterface->GetAdapterDisplayMode(CurRenderDevice, &desktop_mode);
		DisplayFormat = _PresentParameters.BackBufferFormat = desktop_mode.Format;

		switch (_PresentParameters.BackBufferFormat) {
		case D3DFMT_X8R8G8B8:
		case D3DFMT_A8R8G8B8:
		case D3DFMT_R8G8B8:
			BitDepth = 32;
			break;
		case D3DFMT_A4R4G4B4:
		case D3DFMT_A1R5G5B5:
		case D3DFMT_R5G6B5:
			BitDepth = 16;
			break;
		case D3DFMT_L8:
		case D3DFMT_A8:
		case D3DFMT_P8:
			BitDepth = 8;
			break;
		default:
			return false;
		}

		if (BitDepth == 32 && D3DInterface->CheckDeviceType(
			D3DADAPTER_DEFAULT, D3DDEVTYPE_HAL, desktop_mode.Format, D3DFMT_A8R8G8B8, TRUE) == D3D_OK) {
			_PresentParameters.BackBufferFormat = D3DFMT_A8R8G8B8;
		}

		if (!Find_Z_Mode(DisplayFormat, _PresentParameters.BackBufferFormat, &_PresentParameters.AutoDepthStencilFormat)) {
			if (BitDepth == 32) {
				BitDepth = 16;
				_PresentParameters.BackBufferFormat = D3DFMT_R5G6B5;
				if (!Find_Z_Mode(_PresentParameters.BackBufferFormat, _PresentParameters.BackBufferFormat,
					&_PresentParameters.AutoDepthStencilFormat)) {
					_PresentParameters.AutoDepthStencilFormat = D3DFMT_UNKNOWN;
				}
			} else {
				_PresentParameters.AutoDepthStencilFormat = D3DFMT_UNKNOWN;
			}
		}
	} else {
		Find_Color_And_Z_Mode(ResolutionWidth, ResolutionHeight, BitDepth, &DisplayFormat,
			&_PresentParameters.BackBufferFormat, &_PresentParameters.AutoDepthStencilFormat);
	}

	if (_PresentParameters.AutoDepthStencilFormat == D3DFMT_UNKNOWN) {
			if (BitDepth == 32) {
			_PresentParameters.AutoDepthStencilFormat = D3DFMT_D32;
		} else {
					_PresentParameters.AutoDepthStencilFormat = D3DFMT_D16;
		}
	}

	StringClass display_format;
	StringClass backbuffer_format;
	Get_Format_Name(DisplayFormat, &display_format);
	Get_Format_Name(_PresentParameters.BackBufferFormat, &backbuffer_format);

	bool result;
	if (reset_device)
		result = Reset_Device(restore_assets);
	else
		result = Create_Device();
	return result;
}

