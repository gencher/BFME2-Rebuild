typedef HRESULT(__stdcall *DX8Wrapper_SetIndicesFn)(IDirect3DDevice9 *, void *);

void DXWrapper::Release_Device(void)
{
	if (D3DDevice) {
		for (unsigned a = 0; a < MAX_TEXTURE_STAGES; ++a) {
			// Release references to any textures that were used in the last rendering call.
			((*(DX8Wrapper_SetTextureFn **)D3DDevice)[65])(D3DDevice, a, NULL);
			number_of_DX8_calls++;
		}
		((*(DX8Wrapper_SetStreamSourceFn **)D3DDevice)[100])(D3DDevice, 0, NULL, 0, 0);	// release the reference on the last rendered vertex buffer
		number_of_DX8_calls++;
		((*(DX8Wrapper_SetIndicesFn **)D3DDevice)[104])(D3DDevice, NULL);	// release the reference on the last rendered index buffer
		number_of_DX8_calls++;

		// Release the current vertex and index buffers
		for (unsigned i = 0; i < MAX_VERTEX_STREAMS; ++i) {
			if (render_state.vertex_buffers[i]) {
				render_state.vertex_buffers[i]->Release_Engine_Ref();
			}
			if (render_state.vertex_buffers[i]) {
				render_state.vertex_buffers[i]->Release_Ref();
				render_state.vertex_buffers[i] = NULL;
			}
		}
		if (render_state.index_buffer) {
			render_state.index_buffer->Release_Engine_Ref();
		}
		if (render_state.index_buffer) {
			render_state.index_buffer->Release_Ref();
			render_state.index_buffer = NULL;
		}

		// Shutdown all subsystems
		Do_Onetime_Device_Dependent_Shutdowns();

		// Release the device
		(*(DX8Wrapper_ReleaseFn **)D3DDevice)[2](D3DDevice);
		D3DDevice = NULL;
	}
}

